"""Compare read-structured vs Poisson simulated probe coverage with real MethyLYZR ONT_R10 reads.

Usage: NEUROMETHYL_DATA_ROOT=... python -I validate_read_simulator.py --curve-dir <dir with ONT_R10 feather files> \
           [--union-dir <more extracted dirs>] --out docs/READ_SIMULATOR_VALIDATION.md
The feather files are untrusted data: extract them into a fresh scratch directory first.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "src"))

from neuromethyl_ont.data.array_reference import load_feature_index  # noqa: E402
from neuromethyl_ont.data.paths import get_data_root  # noqa: E402
from neuromethyl_ont.data.read_simulator import ReadModel  # noqa: E402
from neuromethyl_ont.evaluation.read_coverage import (  # noqa: E402
    real_curve,
    seen_epic_ids,
    simulated_read_stats,
)

GRID = [100, 300, 1000, 3000, 10000, 30000, 100000]
SEED = 13


def _fmt(s: dict) -> str:
    return f"{s['frac']:.4f} / {s['mean']:.2f} / {s['sd']:.2f}"


def _cl(s: dict) -> str:
    return f"{s['per_read']:.2f} / {s['run']:.2f}"


def _real_mean(rows: list[dict]) -> dict:
    return {k: float(np.mean([r[k] for r in rows])) for k in rows[0]} if rows else {}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--curve-dir", type=Path, required=True)
    ap.add_argument("--union-dir", type=Path, nargs="*", default=[])
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    root = get_data_root()
    probe_ids = load_feature_index(root / "derived/reference/GSE90496/feature_index.json").probe_ids
    model = ReadModel.from_manifest(probe_ids, root / "references/hg38/HM450.hg38.manifest.tsv.gz")
    curve_files = sorted(args.curve_dir.glob("*.feather"))
    union_files = curve_files + [f for d in args.union_dir for f in sorted(d.glob("*.feather"))]
    seen = seen_epic_ids(union_files)
    in_index = len(seen & set(probe_ids))

    real = real_curve(curve_files, model, probe_ids, GRID, SEED)
    lines = [
        "# Read simulator validation (R13, generated by scripts/evaluation/validate_read_simulator.py)",
        "",
        f"- Index probes: {len(probe_ids)}; with a primary-chromosome hg38 coordinate: "
        f"{len(model.gpos)}; mean probes per simulated read (any length): "
        f"{model.mean_probes_per_read:.2f}.",
        f"- Distinct epic_id in {len(union_files)} real files: {len(seen)}; of these in the index: "
        f"{in_index} ({in_index / len(seen):.1%}); index probes seen in the real files: "
        f"{in_index} ({in_index / len(probe_ids):.1%}).",
        f"- Real curve: {len(curve_files)} files ({', '.join(f.name for f in curve_files)}), "
        f"reads shuffled with seed {SEED}; N = reads covering at least one index probe.",
        "",
        "Coverage: covered fraction of the index probes / mean reads per covered probe / sd of "
        "reads per covered probe.",
        "",
        "| N reads | reads simulated (whole chunks, min 1000) | read-structured | Poisson (same expected observations) "
        "| real (mean over k files) |",
        "|---|---|---|---|---|",
    ]
    cluster = [
        "",
        "Clustering: probe calls per read / covered probes per run of genomically adjacent "
        "covered probes.",
        "",
        "| N reads | read-structured | Poisson | real |",
        "|---|---|---|---|",
    ]
    for n_reads in GRID:
        sim, pois, total = simulated_read_stats(model, n_reads, np.random.default_rng((SEED, n_reads)))
        r = _real_mean(real[n_reads])
        lines.append(
            f"| {n_reads} | {total} | {_fmt(sim)} | {_fmt(pois)} | "
            f"{_fmt(r) + ' (k=' + str(len(real[n_reads])) + ')' if r else 'n/a'} |"
        )
        cluster.append(
            f"| {n_reads} | {_cl(sim)} | {pois['run']:.2f} | "
            f"{_cl(r) if r else 'n/a'} |"
        )
    lines += cluster
    args.out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
